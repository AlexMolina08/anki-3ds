use std::sync::Arc;

use ctru::prelude::*;
use portable_atomic::AtomicU64;
use portable_atomic::Ordering;

fn verify() -> Result<String, Box<dyn std::error::Error>> {
    let payload = b"Original Anki dependency probe: Zstandard on Old Nintendo 3DS";
    let compressed = zstd::bulk::compress(payload, 3)?;
    assert_eq!(zstd::bulk::decompress(&compressed, 1024)?, payload);
    assert!(zstd::bulk::decompress(b"not zstandard", 1024).is_err());
    let atomic = Arc::new(AtomicU64::new(1_u64 << 32));
    let workers: Vec<_> = (0..4)
        .map(|_| {
            let atomic = Arc::clone(&atomic);
            std::thread::spawn(move || {
                for _ in 0..1000 {
                    atomic.fetch_add(1, Ordering::SeqCst);
                }
            })
        })
        .collect();
    for worker in workers {
        worker.join().map_err(|_| "atomic worker panicked")?;
    }
    assert_eq!(atomic.load(Ordering::SeqCst), (1_u64 << 32) + 4000);
    let start = coarsetime::Instant::now();
    std::thread::sleep(std::time::Duration::from_millis(20));
    let elapsed = start.elapsed().as_millis();
    assert!(elapsed >= 10 && elapsed < 1000);
    coarsetime::Instant::update();
    assert!(coarsetime::Instant::recent() >= start);
    coarsetime::Clock::update();
    assert!(coarsetime::Clock::recent_since_epoch().as_secs() > 1_700_000_000);
    anki_3ds_sqlite_vfs::register().map_err(|c| format!("SQLite registration: {c}"))?;
    let db = rusqlite::Connection::open("sdmc:/3ds/anki-3ds/disposable.anki2")?;
    db.execute_batch("PRAGMA locking_mode=EXCLUSIVE; PRAGMA temp_store=MEMORY")?;
    let fields: String = db.query_row(
        include_str!("../../../rslib/src/storage/note/get.sql"),
        [],
        |row| row.get(6),
    )?;
    assert_eq!(
        fields,
        "Old 3DS SQLite fixture\x1fGenerated by upstream Anki"
    );
    db.close().map_err(|(_, e)| e)?;
    Ok(format!("PASS Zstd single-thread roundtrip\nPASS corrupt input rejected\nPASS AtomicU64: 4 Rust threads\nPASS coarsetime: {elapsed} ms\nPASS original SQL via default VFS\nRust Collection remains untested"))
}

fn main() {
    let apt = Apt::new().expect("APT");
    let mut hid = Hid::new().expect("HID");
    let gfx = Gfx::new().expect("GFX");
    let console = Console::new(gfx.top_screen.borrow_mut());
    let mut result = verify().unwrap_or_else(|error| format!("FAIL: {error}"));
    if let Err(error) = std::fs::write("sdmc:/3ds/anki-3ds/runtime-result.txt", &result) {
        result = format!("FAIL: evidence write: {error}");
    }
    console.clear();
    while apt.main_loop() {
        gfx.wait_for_vblank();
        println!("\x1b[1;1H{result}\nSTART exits");
        hid.scan_input();
        if hid.keys_down().contains(KeyPad::START) {
            break;
        }
    }
}
