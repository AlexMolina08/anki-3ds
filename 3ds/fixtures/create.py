"""Create a disposable collection through the installed upstream Anki backend."""
import hashlib
import json
from pathlib import Path

from anki import buildinfo
from anki.collection import Collection

root = Path(__file__).resolve().parents[2]
path = root / "out/3ds/fixtures/disposable.anki2"
path.parent.mkdir(parents=True, exist_ok=True)
if path.exists():
    raise RuntimeError(f"Refusing to overwrite {path}")
collection = Collection(str(path))
note = collection.new_note(collection.models.by_name("Basic"))
note["Front"] = "Old 3DS SQLite fixture"
note["Back"] = "Generated by upstream Anki"
collection.add_note(note, 1)
metadata = {
    "anki_version": buildinfo.version,
    "notes": collection.note_count(),
    "cards": collection.card_count(),
    "note_id": note.id,
    "schema_version": collection.db.scalar("select ver from col"),
}
collection.close()
metadata["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
path.with_suffix(".json").write_text(json.dumps(metadata, indent=2) + "\n")
print(json.dumps(metadata))
