"""Verify the native probe's reviewed collection with upstream desktop Anki.

Reads a copy, so the SD file stays exactly as the console left it.
"""
import json
import shutil
import time
from pathlib import Path

from anki.collection import Collection

root = Path(__file__).resolve().parents[2]
source = root / "out/3ds/emulator/data/azahar-emu/sdmc/3ds/anki-3ds/disposable.anki2"
target = root / f"out/3ds/fixtures/review-roundtrip-{time.time_ns()}.anki2"
if target.exists():
    raise RuntimeError(f"Refusing to overwrite {target}")
for suffix in ("-wal", "-shm"):
    if Path(str(source) + suffix).exists():
        raise RuntimeError(f"Close the probe and checkpoint the collection ({suffix} present)")
shutil.copy2(source, target)

collection = Collection(str(target))
assert collection.note_count() == 1
assert collection.card_count() == 1
assert collection.db.scalar("select count(*) from revlog") == 5
assert collection.db.scalar("PRAGMA quick_check") == "ok"

card = collection.get_card(collection.find_cards("")[0])
assert card.type == 2, card.type  # CardType.REVIEW
assert card.queue == 2, card.queue  # CardQueue.REVIEW
assert card.reps == 5
assert card.lapses == 1, "recovering from a lapse must not clear it"
assert card.ivl > 0, "a recovered card is back on a day interval"
assert card.due > 0
assert collection.db.scalar("select left from cards") == 0

note = collection.get_note(card.nid)
assert note["Front"] == "Old 3DS SQLite fixture"
assert note["Back"] == "Generated by upstream Anki"

first, second, third, fourth, fifth = collection.db.all(
    "select cid, ease, ivl, lastIvl, factor, time, type from revlog order by id"
)
assert first[0] == second[0] == third[0] == fourth[0] == fifth[0] == card.id
assert first[1] == second[1] == fourth[1] == 3, "Good should be recorded as 3"
assert third[1] == 1, "Again is button 1"
assert fifth[1] == 2, "Hard is button 2"
assert first[2] == -600, "a 600s learning step is stored as -600"
assert second[3] == -600, "the previous interval was still the step"
assert first[6] == second[6] == 0, "both answers were learning reviews"
assert third[6] == 1, "a lapse is a review-kind entry"
assert third[2] == -600, "the relearn step is stored as -600"
assert third[3] == second[2], (third[3], second[2])
assert fourth[6] == 2, "recovering from a lapse is a relearning-kind entry"
assert fourth[2] == fifth[3], (fourth[2], fifth[3])
assert fourth[3] == -600, "the previous interval was the relearn step"
assert first[5] == 1500 and second[5] == 2500 and fourth[5] == 3000, (
    first[5],
    second[5],
    fourth[5],
)
assert third[5] == 0, third[5]
assert fifth[5] == 0, fifth[5]
assert fifth[6] == 1, "Hard on a review card is a review-kind entry"
assert fifth[2] == card.ivl, (fifth[2], card.ivl)
assert fifth[3] == fourth[2], "the previous interval was the recovered one"
assert card.ivl >= fourth[2], (card.ivl, fourth[2])

data = json.loads(collection.db.scalar("select data from cards"))
if "s" in data:
    assert data["s"] > 0, data
    assert 1.0 <= data["d"] <= 10.0, data
    assert 0.0 < data["dr"] <= 1.0, data
    assert fifth[4] == round(((data["d"] - 1.0) / 9.0 + 0.1) * 1000), (fifth[4], data)
    assert fifth[4] > fourth[4], (fifth[4], fourth[4])
    fsrs = True
else:
    assert second[4] == 2500, "a graduated card takes the initial SM-2 ease"
    assert third[4] == 2300, (third[4], "a lapse drops the ease by 200")
    assert fourth[4] == third[4], (fourth[4], "recovering does not restore the ease")
    assert fifth[4] == fourth[4] - 150, (fifth[4], "Hard drops the ease by 150")
    fsrs = False
collection.close()

result = {
    "verified_copy": str(target),
    "upstream_anki_reopened_reviewed_collection": True,
    "fsrs_enabled": fsrs,
    "card_type": "REVIEW",
    "card_queue": "REVIEW",
    "card_reps": 5,
    "card_lapses": 1,
    "card_remaining_steps": 0,
    "card_interval_days": card.ivl,
    "revlog_rows": 5,
    "revlog_kinds": [first[6], second[6], third[6], fourth[6], fifth[6]],
    "learning_revlog_interval": first[2],
    "graduated_revlog_interval": second[2],
    "graduated_revlog_ease": second[4],
    "lapse_revlog_interval": third[2],
    "lapse_revlog_ease": third[4],
    "relearned_revlog_interval": fourth[2],
    "relearned_revlog_ease": fourth[4],
    "hardened_revlog_interval": fifth[2],
    "hardened_revlog_ease": fifth[4],
    "card_memory_state": data if fsrs else None,
}
(root / "out/3ds/logs/collection-review-roundtrip.json").write_text(json.dumps(result, indent=2) + "\n")
print(json.dumps(result))
