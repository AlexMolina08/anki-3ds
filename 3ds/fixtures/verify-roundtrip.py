"""Validate a copy of the native probe's disposable collection with upstream Anki."""
import json
import shutil
import sqlite3
import subprocess
import time
from pathlib import Path

from anki.collection import Collection

root = Path(__file__).resolve().parents[2]
source = root / "out/3ds/emulator/data/azahar-emu/sdmc/3ds/anki-3ds/disposable.anki2"
original = root / "out/3ds/fixtures/disposable.anki2"
target = root / f"out/3ds/fixtures/native-roundtrip-{time.time_ns()}.anki2"
if target.exists():
    raise RuntimeError(f"Refusing to overwrite {target}")
rom = str(root / "out/3ds/sqlite-target/armv6k-nintendo-3ds/release/anki-3ds-sqlite-probe.3dsx")
for line in subprocess.check_output(["ps", "-ax", "-o", "pid=,command="], text=True).splitlines():
    fields = line.split()
    if len(fields) >= 3 and fields[1].endswith("/Contents/MacOS/azahar") and rom in fields[2:]:
        raise RuntimeError("Close the SQLite emulator before copying its collection")
if source.with_suffix(".anki2.lock").exists() or Path(str(source) + "-wal").exists():
    raise RuntimeError("Close the probe and checkpoint its collection before copying")
shutil.copy2(source, target)
with sqlite3.connect(f"file:{original}?mode=ro&immutable=1", uri=True) as before:
    before_cards = before.execute("SELECT * FROM cards").fetchall()
with sqlite3.connect(f"file:{target}?mode=ro&immutable=1", uri=True) as after:
    assert after.execute("SELECT * FROM cards").fetchall() == before_cards
collection = Collection(str(target))
assert collection.note_count() == 1
assert collection.card_count() == 1
metadata = json.loads(original.with_suffix(".json").read_text())
note = collection.get_note(metadata["note_id"])
assert note["Front"] == "Old 3DS SQLite fixture"
assert note["Back"] == "Generated by upstream Anki"
assert note.tags == ["old3ds_probe"]
assert collection.db.scalar("PRAGMA quick_check") == "ok"
collection.close()
result = {"verified_copy": str(target), "upstream_anki_reopened_native_copy": True,
          "notes": 1, "cards": 1, "tag": "old3ds_probe", "card_rows_unchanged": True}
(root / "out/3ds/logs/collection-roundtrip.json").write_text(json.dumps(result, indent=2) + "\n")
print(json.dumps(result))
